"""End-to-end browser check of the app in demo mode (data stays in the test browser).
Run:  python3 -m http.server 8766 --directory public   then   python3 tests/e2e.py
Needs Python Playwright and Chrome. Uses made-up test data only."""
import asyncio, sys, os
from playwright.async_api import async_playwright
BASE = os.environ.get('APP', 'http://localhost:8766/index.html'); SHOTS = os.environ.get('SHOTS', '')
CHROME = os.environ.get('CHROME', '/usr/bin/google-chrome')
fails = []
def check(ok, what):
    print(('  ok   ' if ok else '  FAIL ') + what)
    if not ok: fails.append(what)
async def shot(pg, name, full=False):
    if SHOTS: await pg.screenshot(path=f'{SHOTS}/{name}.png', full_page=full)
async def login(pg, u, p):
    await pg.fill('form[data-form=login] input[name=username]', u); await pg.fill('form[data-form=login] input[name=password]', p)
    await pg.click('form[data-form=login] button.primary'); await pg.wait_for_timeout(1200)

async def main():
    async with async_playwright() as pw:
        b = await pw.chromium.launch(executable_path=CHROME, args=['--no-sandbox'])
        ctx = await b.new_context(viewport={'width': 390, 'height': 844}, locale='en-GB')
        pg = await ctx.new_page(); errs = []
        pg.on('pageerror', lambda e: errs.append(str(e)))
        pg.on('dialog', lambda d: asyncio.ensure_future(d.accept()))
        await pg.add_init_script("localStorage.getItem('tvp_theme')||localStorage.setItem('tvp_theme','dark')")

        print('Public website')
        await pg.goto(BASE); await pg.wait_for_selector('.site')
        check(await pg.locator('.site h1').count() == 1, 'visitor sees the website with one main heading')
        check(await pg.locator('.s-plan').count() >= 1, 'pricing shows the packages from the admin dashboard')
        check(await pg.locator('.s-faq details').count() >= 5, 'FAQ is present')
        await shot(pg, 'site-mobile', True)
        overflow = await pg.evaluate('document.documentElement.scrollWidth > window.innerWidth + 1')
        check(not overflow, 'no sideways scrolling on a phone')
        small = await pg.evaluate("[...document.querySelectorAll('.site .btn, .s-faq summary')].filter(e => e.offsetParent && e.getBoundingClientRect().height < 40).length")
        check(small == 0, 'website buttons are comfortable to tap')
        for page in ['about', 'privacy', 'terms']:
            await pg.click(f'.s-foot [data-page={page}]'); await pg.wait_for_timeout(200)
            check(await pg.locator('.s-doc h1').count() == 1, f'{page} page opens')
            await pg.click('.s-back')
        await pg.click('.s-foot [data-lang=ar]'); await pg.wait_for_timeout(300)
        check(await pg.evaluate('document.documentElement.dir') == 'rtl', 'Arabic switches the layout to right-to-left')
        await shot(pg, 'site-mobile-ar')
        await pg.click('.s-foot [data-lang=fr]'); await pg.wait_for_timeout(200)
        check('Se connecter' in await pg.inner_text('.s-nav'), 'French website')
        await pg.click('.s-foot [data-lang=en]'); await pg.wait_for_timeout(200)
        await pg.set_viewport_size({'width': 1280, 'height': 800}); await pg.wait_for_timeout(200); await shot(pg, 'site-desktop')
        await pg.set_viewport_size({'width': 390, 'height': 844})

        print('Sign-in help')
        await pg.click('.s-nav [data-act=site-login]'); await pg.wait_for_selector('form[data-form=login]')
        await pg.click('[data-act=forgot]'); await pg.fill('form[data-form=forgot] input', 'nobody'); await pg.click('form[data-form=forgot] button'); await pg.wait_for_timeout(600)
        check(await pg.locator('.modal .notice.success').count() == 1, 'forgot password answers the same for unknown accounts')
        await pg.click('[data-act=close-modal]')
        await login(pg, 'Iptv', 'wrong-password')
        check(await pg.locator('.err-box').count() == 1, 'wrong password shows an error')

        print('Admin')
        await login(pg, 'Iptv', 'Iptv')
        check(await pg.locator('.admin').count() == 1, 'admin signs in')
        await pg.click('[data-act=new-customer]'); await pg.wait_for_selector('form[data-form=customer]')
        await pg.fill('form[data-form=customer] input[name=name]', 'Test Person'); await pg.fill('form[data-form=customer] input[name=username]', 'testuser')
        await pg.fill('form[data-form=customer] input[name=email]', 'test.person@example.com')
        if await pg.locator('form[data-form=customer] input[name=password]').count(): await pg.fill('form[data-form=customer] input[name=password]', 'secret12')
        await pg.evaluate("document.querySelector('form[data-form=customer]').requestSubmit()"); await pg.wait_for_timeout(1500)
        await pg.evaluate("document.querySelector('[data-act=close-modal]')?.click()")
        await pg.evaluate("document.querySelector('#nav [data-tab=finance]').click()"); await pg.wait_for_timeout(1500)
        check('Automatic activation from Stripe' in await pg.inner_text('#admin-body'), 'Stripe automatic activation card is shown, not connected by default')
        await shot(pg, 'admin-autopay', True)
        await pg.evaluate("document.querySelector('#nav [data-tab=security]').click()"); await pg.wait_for_timeout(1000)
        await pg.click('[data-act=tfa-setup]'); await pg.wait_for_selector('form[data-form=tfa-enable]'); await shot(pg, 'admin-2fa-setup')
        secret = (await pg.inner_text('.modal .code')).replace(' ', '')
        code = await pg.evaluate("async (s) => (await import('./core.js')).totp(s)", secret)
        await pg.fill('form[data-form=tfa-enable] input', code); await pg.click('form[data-form=tfa-enable] button'); await pg.wait_for_timeout(1200)
        check(await pg.locator('[data-act=tfa-off]').count() == 1, 'two-step sign-in turns on with a valid code')
        await pg.evaluate("document.querySelector('[data-act=logout]').click()"); await pg.wait_for_timeout(1000)
        if await pg.locator('form[data-form=login]').count() == 0: await pg.click('[data-act=site-login]')
        await login(pg, 'Iptv', 'Iptv')
        check(await pg.locator('form[data-form=login-code]').count() == 1, 'password alone is no longer enough: a code is asked')
        await pg.fill('form[data-form=login-code] input', '000000'); await pg.click('form[data-form=login-code] button'); await pg.wait_for_timeout(600)
        check(await pg.locator('#code-err .err-box').count() == 1, 'wrong code is refused')
        code = await pg.evaluate("async (s) => (await import('./core.js')).totp(s)", secret)
        await pg.fill('form[data-form=login-code] input', code); await pg.click('form[data-form=login-code] button'); await pg.wait_for_timeout(1200)
        check(await pg.locator('.admin').count() == 1, 'right code signs in')
        await pg.evaluate("document.querySelector('[data-act=logout]').click()"); await pg.wait_for_timeout(1000)

        print('Customer')
        await login(pg, 'testuser', 'secret12')
        check(await pg.locator('.uapp').count() == 1, 'customer signs in')
        await pg.click('.bnav [data-tab=account]'); await pg.wait_for_timeout(1200)
        check(await pg.locator('#acc-devices .list-item').count() == 1 and 'This device' in await pg.inner_text('#acc-devices'), 'device list shows this device')
        await pg.click('[data-act=ticket-new]'); await pg.fill('form[data-form=ticket-new] input[name=subject]', 'Channel not working')
        await pg.fill('form[data-form=ticket-new] textarea', 'Channel 5 shows a black screen since this morning.'); await pg.click('form[data-form=ticket-new] button.primary'); await pg.wait_for_timeout(1000)
        check(await pg.locator('#acc-tickets .list-item').count() == 1, 'support request is created and listed')
        check(await pg.locator('#acc-payments').count() == 1, 'payments section is shown')
        await shot(pg, 'customer-account', True)
        await pg.fill('form[data-form=pin-on] input', '1234'); await pg.click('form[data-form=pin-on] button'); await pg.wait_for_timeout(400)
        check(await pg.locator('form[data-form=pin-off]').count() == 1, 'parental PIN turns on')
        await pg.fill('form[data-form=pin-off] input', '0000'); await pg.click('form[data-form=pin-off] button'); await pg.wait_for_timeout(300)
        check(await pg.locator('form[data-form=pin-off]').count() == 1, 'wrong PIN does not turn it off')
        await pg.evaluate("document.querySelector('[data-act=logout]').click()"); await pg.wait_for_timeout(1000)
        check(await pg.locator('form[data-form=login]').count() == 1, 'a device that has signed in before opens the sign-in screen, not the website')

        print('Support desk')
        await login(pg, 'Iptv', 'Iptv'); code = await pg.evaluate("async (s) => (await import('./core.js')).totp(s)", secret)
        await pg.fill('form[data-form=login-code] input', code); await pg.click('form[data-form=login-code] button'); await pg.wait_for_timeout(1200)
        await pg.evaluate("document.querySelector('#nav [data-tab=support]').click()"); await pg.wait_for_timeout(1000)
        check(await pg.locator('#admin-body [data-act=tk-open]').count() == 1, 'admin sees the request')
        await pg.click('#admin-body [data-act=tk-open]'); await pg.fill('form[data-form=tk-reply] textarea', 'Thanks, it is fixed now. Please try again.'); await shot(pg, 'admin-ticket')
        await pg.click('form[data-form=tk-reply] button.primary'); await pg.wait_for_timeout(1000)
        await pg.evaluate("document.querySelector('[data-act=logout]').click()"); await pg.wait_for_timeout(1000)
        await login(pg, 'testuser', 'secret12'); await pg.click('.bnav [data-tab=account]'); await pg.wait_for_timeout(1200)
        check('Answered' in await pg.inner_text('#acc-tickets'), 'customer sees the answer status')
        await pg.click('#acc-tickets [data-act=ticket-open]'); await pg.wait_for_timeout(300)
        check('fixed now' in await pg.inner_text('.modal .thread'), 'customer reads the reply in the app'); await shot(pg, 'customer-ticket')
        check(len(errs) == 0, 'no script errors' + (': ' + errs[0][:160] if errs else ''))
        await b.close()
    print('\n' + ('ALL CHECKS PASSED' if not fails else f'{len(fails)} CHECK(S) FAILED'))
    sys.exit(1 if fails else 0)
asyncio.run(main())
